"""Generates Android string resources for all Khotwa languages.
Run: python3 tools/i18n/generate.py  (from repo root or anywhere)."""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from en_ar import EN, AR
from fr_es import FR, ES
from pt_tr import PT, TR
from id_hi_ur import ID, HI, UR

RES = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main", "res")
LANGS = {"values": EN, "values-ar": AR, "values-fr": FR, "values-es": ES, "values-pt": PT,
         "values-tr": TR, "values-in": ID, "values-hi": HI, "values-ur": UR}

def esc(s):
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    return s

def fmt_args(s):
    return sorted(set(re.findall(r"%(\d)\$([sd])", s)))

def main():
    keys = list(EN.keys())
    for folder, table in LANGS.items():
        missing = [k for k in keys if k not in table]
        extra = [k for k in table if k not in EN]
        assert not extra, (folder, extra)
        for k in keys:
            if k in table and fmt_args(table[k]) != fmt_args(EN[k]):
                raise SystemExit(f"format mismatch {folder}/{k}")
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               "<!-- Generated by tools/i18n/generate.py. Do not edit by hand. -->", "<resources>"]
        for k in keys:
            v = table.get(k, EN[k])
            attr = ' translatable="false"' if folder == "values" and k in ("brand",) and False else ""
            out.append(f'    <string name="{k}"{attr}>{esc(v)}</string>')
        out.append("</resources>")
        d = os.path.join(RES, folder)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
            f.write("\n".join(out) + "\n")
        print(folder, len(keys) - len(missing), "strings", "missing:", missing)

if __name__ == "__main__":
    main()
